const allLists = {
  POPULAR_BOY_NAMES,
  THEME_SOUND_NAMES,
  THEME_KOREAN_NAMES,
  THEME_VIRTUE_NAMES,
  THEME_NATURE_NAMES
};

const counts = {};
const duplicates = [];

Object.entries(allLists).forEach(([listName, list]) => {
  list.forEach(name => {
    const cleanName = name.startsWith('조') ? name.slice(1) : name;
    if (!counts[cleanName]) {
      counts[cleanName] = [];
    }
    counts[cleanName].push(listName);
  });
});

Object.entries(counts).forEach(([name, lists]) => {
  if (lists.length > 1) {
    duplicates.push({ name, lists });
  }
});

